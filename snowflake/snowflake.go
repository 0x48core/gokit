// Package snowflake generates unique, roughly time-ordered 64-bit IDs.
//
// An ID is a positive int64 laid out as:
//
//	0 | 41 bits: milliseconds since epoch | 10 bits: node ID | 12 bits: sequence
//
// which gives about 69 years of IDs per epoch, up to 1024 nodes, and up to 4096 IDs
// per millisecond per node.
package snowflake

import (
	"errors"
	"fmt"
	"sync"
	"time"
)

const (
	timeBits     = 41
	nodeBits     = 10
	sequenceBits = 12

	// MaxNodeID is the largest node ID a Node accepts.
	MaxNodeID = 1<<nodeBits - 1

	maxSequence = 1<<sequenceBits - 1
	maxElapsed  = 1<<timeBits - 1

	nodeShift = sequenceBits
	timeShift = sequenceBits + nodeBits
)

// DefaultEpoch is the epoch used when no WithEpoch option is given.
var DefaultEpoch = time.Date(2026, time.January, 1, 0, 0, 0, 0, time.UTC)

var (
	// ErrInvalidNodeID is returned when a node ID is outside [0, MaxNodeID].
	ErrInvalidNodeID = errors.New("snowflake: invalid node ID")
	// ErrInvalidEpoch is returned when the epoch is in the future.
	ErrInvalidEpoch = errors.New("snowflake: epoch is in the future")
	// ErrTimeOverflow is returned once the 41-bit time range since the epoch is used up.
	ErrTimeOverflow = errors.New("snowflake: time since epoch exceeds 41 bits")
	// ErrLeaseLost is returned when the node ID lease from a NodeRegistry is lost,
	// because another node may now be using the same node ID.
	ErrLeaseLost = errors.New("snowflake: node ID lease lost")
)

// Option configures a Node.
type Option func(*config)

type config struct {
	epoch time.Time
	lost  <-chan struct{}
}

// WithEpoch sets the time IDs are counted from. Every node generating IDs for the
// same keyspace must use the same epoch.
func WithEpoch(epoch time.Time) Option {
	return func(c *config) {
		c.epoch = epoch
	}
}

func withLeaseLost(lost <-chan struct{}) Option {
	return func(c *config) {
		c.lost = lost
	}
}

// Node generates IDs for a single node ID. It is safe for concurrent use.
type Node struct {
	mu       sync.Mutex
	epoch    time.Time
	start    time.Time // epoch carrying a monotonic clock reading
	nodeID   int64
	lastMs   int64
	sequence int64
	lost     <-chan struct{}
	now      func() time.Time
}

// New creates a Node with the given node ID. Two nodes running at the same time must
// never share a node ID; use NewWithRegistry to have one assigned automatically.
func New(nodeID int64, opts ...Option) (*Node, error) {
	if nodeID < 0 || nodeID > MaxNodeID {
		return nil, fmt.Errorf("%w: %d, must be in [0, %d]", ErrInvalidNodeID, nodeID, MaxNodeID)
	}

	cfg := config{epoch: DefaultEpoch}
	for _, opt := range opts {
		opt(&cfg)
	}

	now := time.Now()
	if cfg.epoch.After(now) {
		return nil, fmt.Errorf("%w: %s", ErrInvalidEpoch, cfg.epoch)
	}

	return &Node{
		epoch: cfg.epoch,
		// Measure time from the epoch using the monotonic clock, so wall clock
		// adjustments (NTP, manual changes) can't make IDs go backwards.
		start:  now.Add(cfg.epoch.Sub(now)),
		nodeID: nodeID,
		lastMs: -1,
		lost:   cfg.lost,
		now:    time.Now,
	}, nil
}

// NodeID returns the node ID embedded in every ID this Node generates.
func (n *Node) NodeID() int64 {
	return n.nodeID
}

// Generate returns a new unique ID. If 4096 IDs were already generated in the
// current millisecond, it waits for the next one.
func (n *Node) Generate() (int64, error) {
	select {
	case <-n.lost:
		return 0, ErrLeaseLost
	default:
	}

	n.mu.Lock()
	defer n.mu.Unlock()

	elapsed := n.now().Sub(n.start)
	ms := max(elapsed.Milliseconds(), n.lastMs)

	if ms == n.lastMs {
		n.sequence = (n.sequence + 1) & maxSequence
		if n.sequence == 0 {
			for ms <= n.lastMs {
				time.Sleep(time.Duration(n.lastMs+1)*time.Millisecond - elapsed)
				elapsed = n.now().Sub(n.start)
				ms = elapsed.Milliseconds()
			}
		}
	} else {
		n.sequence = 0
	}

	if ms > maxElapsed {
		return 0, ErrTimeOverflow
	}
	n.lastMs = ms

	return ms<<timeShift | n.nodeID<<nodeShift | n.sequence, nil
}

// Parse splits an ID generated by this Node into its parts.
func (n *Node) Parse(id int64) Parts {
	return Parse(id, n.epoch)
}

// Parts are the components of an ID.
type Parts struct {
	Time     time.Time
	NodeID   int64
	Sequence int64
}

// Parse splits an ID into its parts. epoch must be the epoch the ID was generated with.
func Parse(id int64, epoch time.Time) Parts {
	return Parts{
		Time:     epoch.Add(time.Duration(id>>timeShift) * time.Millisecond),
		NodeID:   id >> nodeShift & MaxNodeID,
		Sequence: id & maxSequence,
	}
}
